#!/usr/bin/env python3
"""Regenerate tables.json from TrainingRooms' own source: fighter kinds and CSS tiles, stage ids and SSS tiles.

    python3 -I build_tables.py <TrainingRooms checkout> [--out tables.json]

Sources (never memory, HARNESS-LESSONS "Verify, don't recall"):
  src/model/swap/roster_grid.rs  GRID: the native character select in row-major tile order (Mario 0, Lucas 39,
                                 Steve 78 and the Random/All tile 86 match the tile cursor's settled lines on Eden).
  src/model/stages/lobby_stages.rs  STAGES: ui_stage_db can_select stages in disp_order with their native stage ids.
The Training stage select puts the Training stage on tile 0 and STAGES[k] on tile k for k >= 1 (its first entry,
Waiting Room, is the plugin's own default and has no tile there). Each SSS tile is marked "proven" only where an Eden
run showed it; tables.json keeps that evidence beside the derived index, and pick_stage refuses an unproven tile
unless the row asks for "allow_derived": true and confirms the stage id from game state after the load.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

PROVEN_SSS = {
    0: 'rc15-tech-s0-direct-99ed57de-chord1 (XPS, 2026-11-16): native-training-name gate on entry, tile 0',
    1: 'rc15-tech-s0-direct-99ed57de-chord1: settled screen=sss at=1, native-battlefield-name gate passed; '
       'harness-lib-xps-1: camera_setup stage=0 after the load',
    4: 'harness-lib-xps-1 (XPS, 2026-11-16 03:18Z): settled at=4, still names Final Destination, and after the load '
       'camera_setup stage=3',
    6: 'rc15-mashout-grab-135a130f-unstick10-1 (Yoga, 2026-11-16): settled at=6; still names Kongo Jungle',
}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def fighters(text):
    body = text[text.index('const GRID'):]
    body = body[:body.index('];')]
    cells = []
    for item in re.finditer(r'f\(\s*(0x[0-9a-fA-F]+)\s*,\s*"([^"]+)"\s*\)|Slot::Shared\(Group::(\w+)\)|Slot::All', body):
        if item.group(1):
            cells.append({'tile': len(cells), 'kind': int(item.group(1), 16), 'name': item.group(2)})
        elif item.group(3):
            cells.append({'tile': len(cells), 'shared': item.group(3)})
        else:
            cells.append({'tile': len(cells), 'random': True})
    return cells


def stages(text):
    body = text[text.index('pub const STAGES'):]
    body = body[:body.index('];')]
    return [{'id': int(m.group(1)), 'name': m.group(2)} for m in re.finditer(r'\((\d+),\s*"([^"]+)"\)', body)]


def roster_catalog(text):
    body = text[text.index('const CHOICES'):]
    body = body[:body.index('];')]
    result = [{'kind': int(m.group(1), 16), 'name': m.group(2)}
              for m in re.finditer(r'\((0x[0-9a-fA-F]+),\s*"([^"]+)"\)', body)]
    if not result or len({row['kind'] for row in result}) != len(result):
        raise ValueError('invalid TrainingRooms roster catalog')
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('checkout')
    parser.add_argument('--out', default=str(Path(__file__).with_name('tables.json')))
    parser.add_argument('--catalog-only', action='store_true')
    args = parser.parse_args()
    root = Path(args.checkout)
    grid = root / 'src/model/swap/roster_grid.rs'
    catalog = root / 'src/model/swap/choices.rs'
    lobby = root / 'src/model/stages/lobby_stages.rs'
    commit = subprocess.run(['git', '-C', str(root), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
    if args.catalog_only:
        out = json.loads(Path(args.out).read_text())
        out['source'].update({'choices.rs': sha(catalog), 'choices_checkout': str(root), 'choices_commit': commit})
        out['roster_catalog'] = roster_catalog(catalog.read_text())
        Path(args.out).write_text(json.dumps(out, indent=1) + '\n')
        print(f'{len(out["roster_catalog"])} roster choices, commit {commit[:8]} -> {args.out}')
        return
    css = fighters(grid.read_text())
    listed = stages(lobby.read_text())
    sss = [{'tile': 0, 'id': 308, 'name': 'Training'}]
    for index, entry in enumerate(listed):
        if index == 0 or entry['name'] == 'Training':
            continue  # Waiting Room is TR's own default; Training is tile 0 on this screen
        sss.append({'tile': index, **entry})
    for entry in sss:
        if entry['tile'] in PROVEN_SSS:
            entry['proven'] = PROVEN_SSS[entry['tile']]
    out = {
        'about': 'Generated by build_tables.py from TrainingRooms source; do not edit by hand. Kinds are native '
                 'fighter kind ids; stage ids are native stage ids (app::sv_information::stage_id).',
        'source': {'checkout': str(root), 'commit': commit,
                   'roster_grid.rs': sha(grid), 'lobby_stages.rs': sha(lobby), 'choices.rs': sha(catalog)},
        'css_tiles': css,
        'roster_catalog': roster_catalog(catalog.read_text()),
        'sss_training_tiles': sss,
        'forms': ['Normal', 'Omega', 'Battlefield'],
    }
    Path(args.out).write_text(json.dumps(out, indent=1) + '\n')
    print(f'{len(css)} css tiles, {len(sss)} sss tiles, commit {commit[:8]} -> {args.out}')


if __name__ == '__main__':
    main()
